-- ================================================================
-- Migration 0009 — Merchant Commission Receivable (MERCHANT owes NANASHI)
-- ================================================================
-- The opposite financial direction from MERCHANT_PAYOUTS (Nanashi owes
-- merchant). Only ever accrues for merchant orders paid DIRECTLY to the
-- merchant (Bank Transfer / Pay on Delivery / Pay on Pickup) — an Online
-- Payment order never generates a receivable here, since Nanashi already
-- collected that money and can net the commission at payout time. See
-- Backend/modules/merchantFinance.module.js, the single place this rule
-- is encoded, and Database/schema/008_platform_ops.sql for full
-- column-level rationale (this migration mirrors that file exactly).
--
-- Purely additive, idempotent, safe to re-run:
--   1. MERCHANT_COMMISSION_STATEMENTS — new table.
--   2. MERCHANT_COMMISSION_STATEMENT_ITEMS — new table (proves which
--      merchant orders are on which statement; UNIQUE(merchant_order_id)
--      is the double-charge guard — an order can be billed once, ever).
--   3. MERCHANT_COMMISSION_PAYMENTS — new table, supports partial payment.
--   4. PLATFORM_SETTINGS gains a `commission_due_days` row (default 30) —
--      reuses the existing settings table/pattern, not a new mechanism.
--
-- NOT DONE HERE, BY DESIGN: no statements are generated by this
-- migration — issuing a statement is an explicit admin action
-- (POST /api/admin/merchants/:id/commission-statements), never automatic.
-- No merchant order's commission is silently marked owed or paid.
-- ================================================================

-- Select your NanashiCollectibles/GamerTavern database before running this script.
-- USE `nanashi_collectibles`;


CREATE TABLE IF NOT EXISTS MERCHANT_COMMISSION_STATEMENTS (
  ID                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ID       INT UNSIGNED NOT NULL,
  PERIOD_START      DATE NOT NULL,
  PERIOD_END        DATE NOT NULL,
  ISSUE_DATE        DATE NOT NULL,
  DUE_DATE          DATE NOT NULL,
  GROSS_SALES       DECIMAL(10,2) NOT NULL DEFAULT 0,
  COMMISSION_AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
  AMOUNT_PAID       DECIMAL(10,2) NOT NULL DEFAULT 0,
  BALANCE_DUE       DECIMAL(10,2) NOT NULL DEFAULT 0,
  STATUS            VARCHAR(20) NOT NULL DEFAULT 'OPEN',
  CREATED_AT        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_MERCHANT_COMMISSION_STATEMENTS_MERCHANT
    FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANTS(ID) ON DELETE CASCADE,
  INDEX IDX_MCS_MERCHANT (MERCHANT_ID),
  INDEX IDX_MCS_STATUS (STATUS),
  INDEX IDX_MCS_DUE_DATE (DUE_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MERCHANT_COMMISSION_STATEMENT_ITEMS (
  ID                INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  STATEMENT_ID      INT UNSIGNED NOT NULL,
  MERCHANT_ORDER_ID INT UNSIGNED NOT NULL,
  GROSS_AMOUNT      DECIMAL(10,2) NOT NULL,
  COMMISSION_AMOUNT DECIMAL(10,2) NOT NULL,
  CREATED_AT        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_MCSI_STATEMENT
    FOREIGN KEY (STATEMENT_ID) REFERENCES MERCHANT_COMMISSION_STATEMENTS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_MCSI_MERCHANT_ORDER
    FOREIGN KEY (MERCHANT_ORDER_ID) REFERENCES MERCHANT_ORDERS(ID) ON DELETE RESTRICT,
  UNIQUE KEY UQ_MCSI_MERCHANT_ORDER (MERCHANT_ORDER_ID),
  INDEX IDX_MCSI_STATEMENT (STATEMENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS MERCHANT_COMMISSION_PAYMENTS (
  ID                  INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ID         INT UNSIGNED NOT NULL,
  STATEMENT_ID        INT UNSIGNED NOT NULL,
  AMOUNT              DECIMAL(10,2) NOT NULL,
  PAYMENT_METHOD      VARCHAR(30) NULL,
  REFERENCE           VARCHAR(100) NULL,
  PAID_AT             DATE NOT NULL,
  RECORDED_BY_USER_ID INT UNSIGNED NOT NULL,
  NOTES               VARCHAR(500) NULL,
  CREATED_AT          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_MCP_MERCHANT
    FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANTS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_MCP_STATEMENT
    FOREIGN KEY (STATEMENT_ID) REFERENCES MERCHANT_COMMISSION_STATEMENTS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_MCP_RECORDED_BY
    FOREIGN KEY (RECORDED_BY_USER_ID) REFERENCES USERS(ID) ON DELETE RESTRICT,
  INDEX IDX_MCP_MERCHANT (MERCHANT_ID),
  INDEX IDX_MCP_STATEMENT (STATEMENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

INSERT INTO PLATFORM_SETTINGS (SETTING_KEY, SETTING_VALUE, DESCRIPTION)
SELECT 'commission_due_days', '30', 'Days after a commission statement is issued before it becomes due (payment terms) — see MERCHANT_COMMISSION_STATEMENTS.'
 WHERE NOT EXISTS (SELECT 1 FROM PLATFORM_SETTINGS WHERE SETTING_KEY = 'commission_due_days');

