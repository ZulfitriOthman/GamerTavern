-- ================================================================
-- 4. FORWARD-REFERENCE FOREIGN KEYS (EVENT_SEATS -> TICKET_HOLDS / TICKET_ORDER_ITEMS)
-- ================================================================
-- No "ADD CONSTRAINT IF NOT EXISTS" exists in MySQL, so this is guarded
-- with an information_schema check instead — same pattern as migration
-- 0001's MERCHANT_BANK_DETAILS columns.

SET @fk_exists := (
  SELECT COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
   WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'EVENT_SEATS'
     AND CONSTRAINT_NAME = 'FK_EVENT_SEATS_HOLD'
);

SET @ddl := IF(@fk_exists = 0,
  'ALTER TABLE EVENT_SEATS
     ADD CONSTRAINT FK_EVENT_SEATS_HOLD
       FOREIGN KEY (CURRENT_HOLD_ID) REFERENCES TICKET_HOLDS(ID) ON DELETE SET NULL,
     ADD CONSTRAINT FK_EVENT_SEATS_ORDER_ITEM
       FOREIGN KEY (ORDER_ITEM_ID) REFERENCES TICKET_ORDER_ITEMS(ID) ON DELETE SET NULL',
  'SELECT ''EVENT_SEATS forward-reference FKs already exist — skipped'' AS notice'
);

PREPARE stmt FROM @ddl;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;


