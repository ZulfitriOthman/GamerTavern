-- ================================================================
-- Migration 0002 — Add ticketing (concert seat selection and booking)
-- ================================================================
-- Purely additive: 13 new tables (VENUE_LAYOUTS, VENUE_SECTIONS,
-- VENUE_SEATS, EVENTS, TICKET_TYPES, EVENT_SECTIONS, EVENT_SEATS,
-- TICKET_HOLD_SESSIONS, TICKET_HOLDS, TICKET_ORDERS, TICKET_ORDER_ITEMS,
-- TICKET_PAYMENT_TRANSACTIONS, EVENT_TICKETS), no existing table is
-- dropped, renamed, or destructively altered. Nothing here writes to
-- ORDERS/MERCHANT_ORDERS/ORDER_ITEMS/PAYMENT_TRANSACTIONS or any other
-- existing table — ticketing is deliberately a separate order/inventory/
-- payment-record system, see the header of schema/009_ticketing.sql for
-- why (including why PAYMENT_TRANSACTIONS specifically can't be reused:
-- its ORDER_ID is NOT NULL and FK-bound to ORDERS).
--
-- Fresh installs don't need this file — Database/All.sql already
-- includes schema/009_ticketing.sql directly. This migration is for an
-- EXISTING database (e.g. a developer's local nanashi_collectibles that
-- was provisioned before ticketing existed).
--
-- Idempotent: every table uses CREATE TABLE IF NOT EXISTS; the two
-- forward-reference foreign keys at the end are guarded with an
-- information_schema check, same pattern as migration 0001. Safe to
-- re-run if partially applied.
-- ================================================================

-- Select your NanashiCollectibles/GamerTavern database before running this script.
-- USE `your_gamertavern_schema`;


-- ================================================================
-- 1. VENUE GEOMETRY (reusable across events)
-- ================================================================

CREATE TABLE IF NOT EXISTS VENUE_LAYOUTS (
  ID               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  NAME             VARCHAR(150) NOT NULL,
  SLUG             VARCHAR(180) NOT NULL,
  CANVAS_WIDTH     INT UNSIGNED NOT NULL,
  CANVAS_HEIGHT    INT UNSIGNED NOT NULL,
  LAYOUT_ELEMENTS  LONGTEXT NULL,
  TOTAL_CAPACITY   INT UNSIGNED NOT NULL,
  STATUS           VARCHAR(20) NOT NULL DEFAULT 'active',
  CREATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY UQ_VENUE_LAYOUTS_SLUG (SLUG)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS VENUE_SECTIONS (
  ID               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  VENUE_LAYOUT_ID  INT UNSIGNED NOT NULL,
  CODE             VARCHAR(20)  NOT NULL,
  NAME             VARCHAR(100) NOT NULL,
  CATEGORY         VARCHAR(20)  NOT NULL,
  CAPACITY         INT UNSIGNED NOT NULL,
  ROWS_COUNT       INT UNSIGNED NULL,
  SEATS_PER_ROW    INT UNSIGNED NULL,
  POSITION_X       INT NOT NULL,
  POSITION_Y       INT NOT NULL,
  WIDTH            INT UNSIGNED NOT NULL,
  HEIGHT           INT UNSIGNED NOT NULL,
  SORT_ORDER       INT UNSIGNED NOT NULL DEFAULT 0,
  STATUS           VARCHAR(20) NOT NULL DEFAULT 'active',
  CREATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_VENUE_SECTIONS_LAYOUT
    FOREIGN KEY (VENUE_LAYOUT_ID) REFERENCES VENUE_LAYOUTS(ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_VENUE_SECTIONS_LAYOUT_CODE (VENUE_LAYOUT_ID, CODE),
  INDEX IDX_VENUE_SECTIONS_LAYOUT (VENUE_LAYOUT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS VENUE_SEATS (
