CREATE TABLE COUNTRIES (
  ID            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  NAME          VARCHAR(100) NOT NULL,
  ISO_CODE      CHAR(2)      NOT NULL,                           -- ISO 3166-1 alpha-2, e.g. 'BN'
  CALLING_CODE  VARCHAR(10)  NOT NULL,                           -- e.g. '+673'
  FLAG          VARCHAR(10)  NULL,                                -- FLAG emoji, e.g. '🇧🇳'
  CREATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY UQ_COUNTRIES_ISO_CODE (ISO_CODE),
  INDEX IDX_COUNTRIES_CALLING_CODE (CALLING_CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
