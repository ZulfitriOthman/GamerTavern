CREATE TABLE ENQUIRIES (
  ID          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  SERVICE_ID  INT UNSIGNED NULL,                                   -- nullable: not every enquiry is about a service
  TOPIC       VARCHAR(30) NOT NULL,                                -- 'general' | 'shop' | 'tcg' | 'esports' | 'service' — app-validated
  NAME        VARCHAR(100) NOT NULL,
  EMAIL       VARCHAR(100) NOT NULL,
  PHONE       VARCHAR(20) NULL,
  MESSAGE     TEXT NOT NULL,
  STATUS      VARCHAR(20) NOT NULL DEFAULT 'new',                  -- 'new' | 'in_progress' | 'resolved' | 'closed'
  CREATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_ENQUIRIES_SERVICE
    FOREIGN KEY (SERVICE_ID) REFERENCES SERVICES(ID) ON DELETE SET NULL,
  INDEX IDX_ENQUIRIES_SERVICE (SERVICE_ID),
  INDEX IDX_ENQUIRIES_TOPIC (TOPIC),
  INDEX IDX_ENQUIRIES_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- Enquiries contain PII (NAME/EMAIL/PHONE/MESSAGE) — never broadcast over
-- Socket.IO (see Backend/controllers/services.controller.js).

