CREATE TABLE DECK_LISTS (
  ID           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TCG_GAME_ID  INT UNSIGNED NOT NULL,
  CREATED_BY   INT UNSIGNED NULL,
  NAME         VARCHAR(255) NOT NULL,
  ARCHETYPE    VARCHAR(100) NULL,
  FORMAT       VARCHAR(100) NULL,
  PILOT        VARCHAR(100) NULL,
  DESCRIPTION  TEXT NULL,
  KEY_CARDS    TEXT NULL,
  WIN_RATE     DECIMAL(5,2) NULL,
  POPULARITY   INT UNSIGNED NULL,
  AVG_COST     DECIMAL(10,2) NULL,
  FEATURED     TINYINT(1) NOT NULL DEFAULT 0,
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_DECK_LISTS_TCG_GAME
    FOREIGN KEY (TCG_GAME_ID) REFERENCES TCG_GAMES(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_DECK_LISTS_CREATED_BY
    FOREIGN KEY (CREATED_BY) REFERENCES USERS(ID) ON DELETE SET NULL,
  INDEX IDX_DECK_LISTS_TCG_GAME (TCG_GAME_ID),
