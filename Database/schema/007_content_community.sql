  INDEX IDX_DECK_LISTS_FEATURED (FEATURED)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TOURNAMENTS (
  ID                     INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ESPORTS_GAME_ID        INT UNSIGNED NOT NULL,
  NAME                   VARCHAR(255) NOT NULL,
  SLUG                   VARCHAR(280) NOT NULL,
  DESCRIPTION            LONGTEXT NULL,
  LOCATION               VARCHAR(255) NULL,
  ENTRY_FEE              DECIMAL(10,2) NULL,
  ORGANIZER              VARCHAR(100) NULL,
  RULES                  LONGTEXT NULL,
  REGISTRATION_DEADLINE  TIMESTAMP NULL,
  REGISTRATION_TYPE      VARCHAR(20) NOT NULL DEFAULT 'individual', -- 'individual' | 'team'
  TEAM_SIZE              INT UNSIGNED NULL,                          -- required (app-level) when REGISTRATION_TYPE = 'team'
  MAX_ENTRIES            INT UNSIGNED NULL,                          -- max registrants (individual) OR max teams (team)
  STATUS                 VARCHAR(20) NOT NULL DEFAULT 'draft',       -- draft|open|closed|completed|cancelled
  START_DATE             TIMESTAMP NULL,
  END_DATE               TIMESTAMP NULL,
  CREATED_AT             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_TOURNAMENTS_ESPORTS_GAME
    FOREIGN KEY (ESPORTS_GAME_ID) REFERENCES ESPORTS_GAMES(ID) ON DELETE RESTRICT,
  UNIQUE KEY UQ_TOURNAMENTS_SLUG (SLUG),
  INDEX IDX_TOURNAMENTS_ESPORTS_GAME (ESPORTS_GAME_ID),
  INDEX IDX_TOURNAMENTS_STATUS (STATUS),
  INDEX IDX_TOURNAMENTS_START_DATE (START_DATE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TOURNAMENT_REGISTRATIONS (
  ID             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TOURNAMENT_ID  INT UNSIGNED NOT NULL,
  USER_ID        INT UNSIGNED NULL,
  GUEST_NAME     VARCHAR(100) NULL,                                -- set when USER_ID IS NULL (guest participant)
  NICKNAME       VARCHAR(100) NULL,
  STATUS         VARCHAR(20) NOT NULL DEFAULT 'registered',        -- registered|checked_in|withdrawn|disqualified
  REGISTERED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_REGISTRATIONS_TOURNAMENT
    FOREIGN KEY (TOURNAMENT_ID) REFERENCES TOURNAMENTS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_REGISTRATIONS_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE SET NULL,
  UNIQUE KEY UQ_REGISTRATIONS_TOURNAMENT_USER (TOURNAMENT_ID, USER_ID),
  UNIQUE KEY UQ_REGISTRATIONS_ID_TOURNAMENT (ID, TOURNAMENT_ID),        -- composite candidate key for TOURNAMENT_TEAMS/TOURNAMENT_TEAM_MEMBERS below
  INDEX IDX_REGISTRATIONS_TOURNAMENT (TOURNAMENT_ID),
  INDEX IDX_REGISTRATIONS_USER (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TOURNAMENT_TEAMS (
  ID                       INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TOURNAMENT_ID            INT UNSIGNED NOT NULL,
  NAME                     VARCHAR(255) NOT NULL,
  CAPTAIN_REGISTRATION_ID  INT UNSIGNED NULL,
  STATUS                   VARCHAR(20) NOT NULL DEFAULT 'registered',
  CREATED_AT               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_TEAMS_TOURNAMENT
    FOREIGN KEY (TOURNAMENT_ID) REFERENCES TOURNAMENTS(ID) ON DELETE CASCADE,
  -- Plain FK on CAPTAIN_REGISTRATION_ID only (not composite): the invariants
  -- "captain belongs to the tournament" and "captain is an actual member of
  -- THIS team" are enforced in backend service logic, not by MySQL — see
  -- Database/README.md.
  CONSTRAINT FK_TEAMS_CAPTAIN_REGISTRATION
    FOREIGN KEY (CAPTAIN_REGISTRATION_ID)
    REFERENCES TOURNAMENT_REGISTRATIONS(ID) ON DELETE SET NULL,
  UNIQUE KEY UQ_TEAMS_TOURNAMENT_NAME (TOURNAMENT_ID, NAME),
  UNIQUE KEY UQ_TEAMS_ID_TOURNAMENT (ID, TOURNAMENT_ID),           -- composite candidate key for TOURNAMENT_TEAM_MEMBERS below
  INDEX IDX_TEAMS_TOURNAMENT (TOURNAMENT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE TOURNAMENT_TEAM_MEMBERS (
  ID               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  TOURNAMENT_ID    INT UNSIGNED NOT NULL,                          -- redundant by design: lets both composite FKs below be enforced by MySQL itself
  TEAM_ID          INT UNSIGNED NOT NULL,
  REGISTRATION_ID  INT UNSIGNED NOT NULL,
  JOINED_AT        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_TEAM_MEMBERS_TEAM
    FOREIGN KEY (TEAM_ID, TOURNAMENT_ID)
    REFERENCES TOURNAMENT_TEAMS(ID, TOURNAMENT_ID) ON DELETE CASCADE,
  CONSTRAINT FK_TEAM_MEMBERS_REGISTRATION
    FOREIGN KEY (REGISTRATION_ID, TOURNAMENT_ID)
    REFERENCES TOURNAMENT_REGISTRATIONS(ID, TOURNAMENT_ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_TEAM_MEMBERS_REGISTRATION (REGISTRATION_ID),       -- a registration belongs to at most one team, ever
  INDEX IDX_TEAM_MEMBERS_TEAM (TEAM_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- BACKEND REQUIREMENT (transactional): creating a team registration — the
-- team row, each member's registration row, each TOURNAMENT_TEAM_MEMBERS
-- row, and the captain assignment — must happen in a single DB transaction.

