-- ================================================================
-- 005 — ORDERS / CHECKOUT
-- ================================================================
-- One customer order (ORDERS) can contain items from multiple
-- MERCHANTS. Each merchant's slice is a merchant_order — this is
-- what a merchant's dashboard/API can see and act on. Customers see
-- the whole `ORDERS` row; MERCHANTS only ever see their own
-- `MERCHANT_ORDERS` row and its `ORDER_ITEMS`.
--
-- ORDERS, MERCHANT_ORDERS, and ORDER_ITEMS are financial/fulfillment
-- records and are never hard-deleted by application CODE — every FK
-- into them below uses ON DELETE RESTRICT for that REASON.
-- ================================================================

CREATE TABLE CUSTOMER_ADDRESSES (
  ID                    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID               INT UNSIGNED NOT NULL,
  LABEL                 VARCHAR(50)  NULL,
  RECIPIENT_NAME        VARCHAR(100) NOT NULL,
  PHONE                 VARCHAR(20)  NULL,
  ADDRESS_LINE1         VARCHAR(255) NOT NULL,
  ADDRESS_LINE2         VARCHAR(255) NULL,                -- added 2026-09-19 (customer delivery checkout) — unit/floor/building, optional
  DISTRICT              VARCHAR(100) NULL,
  MUKIM                 VARCHAR(100) NULL,
  VILLAGE               VARCHAR(100) NULL,
  POSTCODE              VARCHAR(20)  NULL,
  COUNTRY_CODE          CHAR(2)      NOT NULL DEFAULT 'BN',
  IS_DEFAULT_SHIPPING   TINYINT(1)   NOT NULL DEFAULT 0,
  IS_DEFAULT_BILLING    TINYINT(1)   NOT NULL DEFAULT 0,
  CREATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_CUSTOMER_ADDRESSES_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
  INDEX IDX_CUSTOMER_ADDRESSES_USER (USER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CARTS (
  ID          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  USER_ID     INT UNSIGNED NULL,                        -- NULL for a guest cart
  GUEST_TOKEN CHAR(36)     NULL,                         -- app-generated UUID, stored client-side, for guest CARTS
  STATUS      VARCHAR(20)  NOT NULL DEFAULT 'active',    -- active | converted | abandoned
  CREATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_CARTS_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_CARTS_USER (USER_ID),          -- MySQL does not enforce uniqueness among NULLs, so this never blocks multiple guest CARTS
  UNIQUE KEY UQ_CARTS_GUEST_TOKEN (GUEST_TOKEN),
  INDEX IDX_CARTS_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE CART_ITEMS (
  ID          INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CART_ID     INT UNSIGNED NOT NULL,
  PRODUCT_ID  INT UNSIGNED NOT NULL,
  VARIANT_ID  INT UNSIGNED NULL,
  VARIANT_KEY INT UNSIGNED GENERATED ALWAYS AS (COALESCE(VARIANT_ID, 0)) STORED, -- lets the unique key below treat "no variant" as one consistent VALUE
  QUANTITY    INT UNSIGNED NOT NULL,
  CREATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_CART_ITEMS_CART
    FOREIGN KEY (CART_ID) REFERENCES CARTS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_CART_ITEMS_PRODUCT
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_CART_ITEMS_VARIANT
    FOREIGN KEY (VARIANT_ID) REFERENCES PRODUCT_VARIANTS(ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_CART_ITEMS_CART_PRODUCT_VARIANT (CART_ID, PRODUCT_ID, VARIANT_KEY),
  INDEX IDX_CART_ITEMS_CART (CART_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- Cart pricing is NEVER read from this table at checkout time — checkout
-- always recomputes PRICE/SUBTOTAL/discount/shipping/total from current DB values.

CREATE TABLE SHIPPING_METHODS (
  ID           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  NAME         VARCHAR(100) NOT NULL,
  CODE         VARCHAR(30)  NOT NULL,                   -- 'pickup' | 'local_delivery' | 'courier' | 'international' — app-validated
  DESCRIPTION  VARCHAR(255) NULL,
  BASE_FEE     DECIMAL(10,2) NOT NULL DEFAULT 0,
  STATUS       VARCHAR(20)  NOT NULL DEFAULT 'active',
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY UQ_SHIPPING_METHODS_CODE (CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- CODE = 'pickup' is the only code Backend/modules/fulfilment.module.js
-- treats as fulfilment type PICKUP; every other code is DELIVERY. A row's
-- CODE, not its NAME, is what checkout eligibility keys off.

-- Per-merchant fulfilment enablement — added alongside offline payment
-- methods (Pay on Delivery / Pay on Pickup) so eligibility for both can be
-- computed the same way: added 2026-09-18, mirrors MERCHANT_PAYMENT_METHODS
-- (004_merchants.sql-era design, see 010_merchant_payments.sql) exactly,
-- including the "no row = disabled" convention. Nanashi is multi-merchant —
-- one merchant may not offer delivery while another does, so this is
-- deliberately per-merchant, not a single global on/off toggle.
CREATE TABLE MERCHANT_FULFILMENT_METHODS (
  ID           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ID  INT UNSIGNED NOT NULL,
  METHOD       VARCHAR(20)  NOT NULL,                    -- app-validated: DELIVERY | PICKUP — see Backend/modules/fulfilment.module.js
  ENABLED      TINYINT(1)   NOT NULL DEFAULT 0,
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_MERCHANT_FULFILMENT_METHODS_MERCHANT
    FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANTS(ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_MERCHANT_FULFILMENT_METHODS_MERCHANT_METHOD (MERCHANT_ID, METHOD),
  INDEX IDX_MERCHANT_FULFILMENT_METHODS_MERCHANT (MERCHANT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- No row for a given (MERCHANT_ID, METHOD) means "not configured / not
-- enabled" — application code must treat a missing row the same as
-- ENABLED = 0, never assume a method is on by default.

CREATE TABLE COUPONS (
  ID                    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  CODE                  VARCHAR(50) NOT NULL,
  DESCRIPTION           VARCHAR(255) NULL,
  DISCOUNT_TYPE         VARCHAR(20) NOT NULL,             -- 'percent' | 'fixed'
  DISCOUNT_VALUE        DECIMAL(10,2) NOT NULL,
  MIN_SUBTOTAL          DECIMAL(10,2) NULL,
  MAX_USES              INT UNSIGNED NULL,
  MAX_USES_PER_USER     INT UNSIGNED NULL,
  STARTS_AT             TIMESTAMP NULL,
  ENDS_AT               TIMESTAMP NULL,
  STATUS                VARCHAR(20) NOT NULL DEFAULT 'active',
  CREATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY UQ_COUPONS_CODE (CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- MAX_USES / MAX_USES_PER_USER are enforced in application logic (count
-- rows in COUPON_USAGE below), not as DB constraints.

CREATE TABLE ORDERS (
  ID                    INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ORDER_NUMBER          VARCHAR(30)  NOT NULL,            -- app-generated after insert, e.g. 'NC00001'
  USER_ID               INT UNSIGNED NOT NULL,
  SHIPPING_ADDRESS_ID   INT UNSIGNED NULL,
  BILLING_ADDRESS_ID    INT UNSIGNED NULL,
  SHIPPING_METHOD_ID    INT UNSIGNED NULL,
  COUPON_ID             INT UNSIGNED NULL,
  DELIVERY_INSTRUCTIONS VARCHAR(500) NULL,                -- added 2026-09-19 — customer-entered, one-time per order (not part of the reusable CUSTOMER_ADDRESSES row); only meaningful when the resolved fulfilment type is DELIVERY, but not enforced NULL for Pickup at the DB level (app-validated, see checkout.routes.js)
  SUBTOTAL              DECIMAL(10,2) NOT NULL,
  DISCOUNT_TOTAL        DECIMAL(10,2) NOT NULL DEFAULT 0,
  SHIPPING_TOTAL        DECIMAL(10,2) NOT NULL DEFAULT 0,
  GRAND_TOTAL           DECIMAL(10,2) NOT NULL,
  CURRENCY              CHAR(3) NOT NULL DEFAULT 'BND',
  PAYMENT_STATUS        VARCHAR(20) NOT NULL DEFAULT 'PENDING',        -- PENDING | AUTHORIZED | PAID | FAILED | CANCELLED | REFUNDED | PARTIALLY_REFUNDED
  STATUS                VARCHAR(20) NOT NULL DEFAULT 'PENDING_PAYMENT', -- PENDING_PAYMENT | PAID | PROCESSING | READY | SHIPPED | DELIVERED | CANCELLED | REFUNDED
  PLACED_AT             TIMESTAMP NULL,
  CREATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_ORDERS_USER
    FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_ORDERS_SHIPPING_ADDRESS
    FOREIGN KEY (SHIPPING_ADDRESS_ID) REFERENCES CUSTOMER_ADDRESSES(ID) ON DELETE SET NULL,
  CONSTRAINT FK_ORDERS_BILLING_ADDRESS
    FOREIGN KEY (BILLING_ADDRESS_ID) REFERENCES CUSTOMER_ADDRESSES(ID) ON DELETE SET NULL,
  CONSTRAINT FK_ORDERS_SHIPPING_METHOD
    FOREIGN KEY (SHIPPING_METHOD_ID) REFERENCES SHIPPING_METHODS(ID) ON DELETE SET NULL,
  CONSTRAINT FK_ORDERS_COUPON
    FOREIGN KEY (COUPON_ID) REFERENCES COUPONS(ID) ON DELETE SET NULL,
  UNIQUE KEY UQ_ORDERS_ORDER_NUMBER (ORDER_NUMBER),
  INDEX IDX_ORDERS_USER (USER_ID),
  INDEX IDX_ORDERS_STATUS (STATUS),
  INDEX IDX_ORDERS_PAYMENT_STATUS (PAYMENT_STATUS),
  INDEX IDX_ORDERS_CREATED_AT (CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- Orders always belong to a registered user — guest CARTS are supported,
-- but checkout requires an authenticated account. Guest checkout is a
-- possible future extension, not implemented.

-- Added 2026-09-19 (customer delivery checkout). One optional reference photo
-- per order — "where to leave it" (front gate, reception, etc.), never a
-- product photo. Scoped to ORDER_ID, not MERCHANT_ORDER_ID: fulfilment
-- (shipping method + address + instructions + this photo) is chosen ONCE per
-- checkout for the whole cart under the current "one shipping method per
-- order" model (ORDERS.SHIPPING_METHOD_ID, not per-merchant-order) — see the
-- checkout.routes.js header comment. If fulfilment ever becomes genuinely
-- per-merchant, this table's scope would need to move with it; it does not
-- today. FILE_URL is always a backend-relative path under
-- /public/uploads/delivery-references/ (validated server-side, see
-- checkout.routes.js) — never a client-supplied arbitrary URL, and never a
-- base64 blob stored in the database.
CREATE TABLE ORDER_DELIVERY_ATTACHMENTS (
  ID           INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ORDER_ID     INT UNSIGNED NOT NULL,
  FILE_URL     VARCHAR(255) NOT NULL,
  FILE_TYPE    VARCHAR(30)  NOT NULL,                     -- the validated MIME type at upload time, e.g. 'image/jpeg'
  CREATED_AT   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ORDER_DELIVERY_ATTACHMENTS_ORDER
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE CASCADE,
  UNIQUE KEY UQ_ORDER_DELIVERY_ATTACHMENTS_ORDER (ORDER_ID) -- one reference photo per order for now, per product spec
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE MERCHANT_ORDERS (
  ID                     INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ORDER_NUMBER  VARCHAR(40)  NOT NULL,          -- app-generated after insert, e.g. 'MO000001'
  ORDER_ID               INT UNSIGNED NOT NULL,
  MERCHANT_ID            INT UNSIGNED NOT NULL,
  SUBTOTAL               DECIMAL(10,2) NOT NULL,
  COMMISSION_PERCENT     DECIMAL(5,2)  NOT NULL,         -- snapshot at order time — never recompute later from MERCHANTS.COMMISSION_PERCENT
  COMMISSION_AMOUNT      DECIMAL(10,2) NOT NULL,
  MERCHANT_NET_AMOUNT    DECIMAL(10,2) NOT NULL,
  STATUS                 VARCHAR(20) NOT NULL DEFAULT 'PROCESSING', -- PROCESSING | READY | SHIPPED | DELIVERED | CANCELLED
  CREATED_AT             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_MERCHANT_ORDERS_ORDER
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_MERCHANT_ORDERS_MERCHANT
    FOREIGN KEY (MERCHANT_ID) REFERENCES MERCHANTS(ID) ON DELETE RESTRICT,
  UNIQUE KEY UQ_MERCHANT_ORDERS_NUMBER (MERCHANT_ORDER_NUMBER),
  INDEX IDX_MERCHANT_ORDERS_ORDER (ORDER_ID),
  INDEX IDX_MERCHANT_ORDERS_MERCHANT (MERCHANT_ID),
  INDEX IDX_MERCHANT_ORDERS_STATUS (STATUS)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- A merchant's REST session must only ever SELECT rows here WHERE
-- MERCHANT_ID = <resolved server-side from MERCHANT_USERS>. Never accept
-- MERCHANT_ID from the client.

CREATE TABLE ORDER_ITEMS (
  ID                      INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ORDER_ID                INT UNSIGNED NOT NULL,
  MERCHANT_ORDER_ID       INT UNSIGNED NOT NULL,
  PRODUCT_ID              INT UNSIGNED NOT NULL,
  VARIANT_ID              INT UNSIGNED NULL,
  PRODUCT_NAME_SNAPSHOT   VARCHAR(150) NOT NULL,          -- product NAME/PRICE can change after purchase; the order must not depend on current product data
  SKU_SNAPSHOT            VARCHAR(100) NULL,
  UNIT_PRICE_SNAPSHOT     DECIMAL(10,2) NOT NULL,
  QUANTITY                INT UNSIGNED NOT NULL,
  LINE_TOTAL              DECIMAL(10,2) NOT NULL,
  CREATED_AT              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ORDER_ITEMS_ORDER
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_ORDER_ITEMS_MERCHANT_ORDER
    FOREIGN KEY (MERCHANT_ORDER_ID) REFERENCES MERCHANT_ORDERS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_ORDER_ITEMS_PRODUCT
    FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(ID) ON DELETE RESTRICT,
  CONSTRAINT FK_ORDER_ITEMS_VARIANT
    FOREIGN KEY (VARIANT_ID) REFERENCES PRODUCT_VARIANTS(ID) ON DELETE RESTRICT,
  INDEX IDX_ORDER_ITEMS_ORDER (ORDER_ID),
  INDEX IDX_ORDER_ITEMS_MERCHANT_ORDER (MERCHANT_ORDER_ID),
  INDEX IDX_ORDER_ITEMS_PRODUCT (PRODUCT_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE ORDER_STATUS_HISTORY (
  ID                   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ORDER_ID             INT UNSIGNED NOT NULL,
  MERCHANT_ORDER_ID    INT UNSIGNED NULL,                -- set when the change is a merchant-order-level fulfillment update
  OLD_STATUS           VARCHAR(20) NULL,
  NEW_STATUS           VARCHAR(20) NOT NULL,
  CHANGED_BY_TYPE      VARCHAR(20) NOT NULL,              -- customer | merchant | admin | system
  CHANGED_BY_USER_ID   INT UNSIGNED NULL,
  NOTE                 TEXT NULL,
  CREATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT FK_ORDER_STATUS_HISTORY_ORDER
    FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_ORDER_STATUS_HISTORY_MERCHANT_ORDER
    FOREIGN KEY (MERCHANT_ORDER_ID) REFERENCES MERCHANT_ORDERS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_ORDER_STATUS_HISTORY_USER
    FOREIGN KEY (CHANGED_BY_USER_ID) REFERENCES USERS(ID) ON DELETE SET NULL,
  INDEX IDX_ORDER_STATUS_HISTORY_ORDER (ORDER_ID),
  INDEX IDX_ORDER_STATUS_HISTORY_MERCHANT_ORDER (MERCHANT_ORDER_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
-- CASCADE here is safe: ORDERS/MERCHANT_ORDERS are never hard-deleted by
-- application CODE, so this never actually fires in practice.

CREATE TABLE SHIPMENTS (
  ID                   INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  MERCHANT_ORDER_ID    INT UNSIGNED NOT NULL,
  SHIPPING_METHOD_ID   INT UNSIGNED NULL,
  CARRIER              VARCHAR(100) NULL,
  TRACKING_NUMBER      VARCHAR(100) NULL,
  STATUS               VARCHAR(20) NOT NULL DEFAULT 'PENDING', -- PENDING | SHIPPED | DELIVERED
  SHIPPED_AT           TIMESTAMP NULL,
  DELIVERED_AT         TIMESTAMP NULL,
  CREATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT FK_SHIPMENTS_MERCHANT_ORDER
    FOREIGN KEY (MERCHANT_ORDER_ID) REFERENCES MERCHANT_ORDERS(ID) ON DELETE CASCADE,
  CONSTRAINT FK_SHIPMENTS_SHIPPING_METHOD
    FOREIGN KEY (SHIPPING_METHOD_ID) REFERENCES SHIPPING_METHODS(ID) ON DELETE SET NULL,
